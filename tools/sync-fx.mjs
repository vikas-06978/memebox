// npm run sync-fx: extension/lib/fx-ui.js is a generated copy of extension/lib/fx.js.
// Chrome injects one file only once per page even when two content-script groups list it, and the
// panel (isolated world) and the camera hook (page world) both need the Lights engine.
// Edit lib/fx.js only. A unit test fails if the copy is out of date.
import fs from 'node:fs';
import path from 'node:path';

const lib = path.resolve(import.meta.dirname, '..', 'extension', 'lib');
const HEADER = '// GENERATED from lib/fx.js by `npm run sync-fx`. Do not edit this file: edit lib/fx.js and run the command again.\n';
const source = fs.readFileSync(path.join(lib, 'fx.js'), 'utf8');
fs.writeFileSync(path.join(lib, 'fx-ui.js'), HEADER + source);
console.log('lib/fx-ui.js updated');
