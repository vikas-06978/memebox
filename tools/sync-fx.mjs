// npm run sync-fx: extension/lib/fx-ui.js and music-ui.js are generated copies of lib/fx.js and lib/music.js.
// Chrome injects one file only once per page even when two content-script groups list it, and the
// panel (isolated world) and the call hook (page world) both need the Lights engine and the music.
// Edit lib/fx.js and lib/music.js only. A unit test fails if a copy is out of date.
import fs from 'node:fs';
import path from 'node:path';

const lib = path.resolve(import.meta.dirname, '..', 'extension', 'lib');
for (const name of ['fx', 'music']) {
  const header = `// GENERATED from lib/${name}.js by \`npm run sync-fx\`. Do not edit this file: edit lib/${name}.js and run the command again.\n`;
  fs.writeFileSync(path.join(lib, `${name}-ui.js`), header + fs.readFileSync(path.join(lib, `${name}.js`), 'utf8'));
  console.log(`lib/${name}-ui.js updated`);
}
